// Shared helpers for baking web-game puzzles into C headers (and a JSON twin for the tests).
import fs from 'node:fs';
export function u16(v) { return [v & 0xFF, (v >> 8) & 0xFF]; }
export function rowMask(row, truthy = (v) => !!v) { let m = 0; row.forEach((v, x) => { if (truthy(v)) m |= 1 << x; }); return u16(m); }
export function cArray(name, bytes) {
  const lines = [];
  for (let i = 0; i < bytes.length; i += 16) lines.push('  ' + bytes.slice(i, i + 16).map((b) => '0x' + b.toString(16).padStart(2, '0')).join(', ') + ',');
  return `const uint8_t ${name}[${bytes.length}] = {\n${lines.join('\n')}\n};\n`;
}
export function emit(slug, { defines = {}, arrays = {}, json }) {
  const dir = new URL(`../games/${slug}/`, import.meta.url);
  let h = `/* generated by gameboy/gen/${slug}.mjs - do not edit */\n#ifndef PUZZLES_H\n#define PUZZLES_H\n#include <stdint.h>\n`;
  for (const [k, v] of Object.entries(defines)) h += `#define ${k} ${v}\n`;
  for (const [k, v] of Object.entries(arrays)) h += cArray(k, v);
  h += '#endif\n';
  fs.writeFileSync(new URL('puzzles.h', dir), h);
  fs.writeFileSync(new URL('puzzles.json', dir), JSON.stringify(json));
  const bytes = Object.values(arrays).reduce((a, v) => a + v.length, 0);
  console.log(`${slug}: ${bytes} bytes of puzzles`);
}
// pads a per-puzzle byte list to a fixed stride and concatenates
export function pack(puzzles, stride) {
  const out = [];
  for (const p of puzzles) { if (p.length > stride) throw new Error(`puzzle ${p.length} > stride ${stride}`); out.push(...p, ...new Array(stride - p.length).fill(0)); }
  return out;
}
