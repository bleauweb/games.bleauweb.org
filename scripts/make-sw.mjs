// Writes dist/sw.js: a service worker that precaches every file Vite built, so every game and
// tool keeps working with no signal. Run after `vite build`.
import { readdirSync, statSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { createHash } from 'node:crypto';

const dist = new URL('../dist/', import.meta.url).pathname;
const files = [];
function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else files.push('/' + relative(dist, p).split('\\').join('/'));
  }
}
walk(dist);
const precache = files.filter((f) => f !== '/sw.js' && !f.endsWith('.map') && !f.endsWith('.license') && !f.endsWith('.DS_Store'));
// Every page must register the worker, or it would not work offline on its own.
const pages = precache.filter((f) => f.endsWith('.html'));
// Vite bundles shared/pwa.js into each page's chunks, so follow the page's script tags.
const registers = (page) => {
  const html = readFileSync(join(dist, page), 'utf8');
  const srcs = [
    ...[...html.matchAll(/<script[^>]+src="([^"]+)"/g)].map((m) => m[1]),
    ...[...html.matchAll(/<link[^>]+rel="modulepreload"[^>]+href="([^"]+)"/g)].map((m) => m[1]),
  ];
  return srcs.some((src) => {
    try { return readFileSync(join(dist, src), 'utf8').includes('serviceWorker'); } catch { return false; }
  });
};
const missing = pages.filter((f) => !registers(f));
if (missing.length) {
  console.error('Pages without the service-worker registration:', missing);
  process.exit(1);
}
const version = createHash('sha256').update(precache.map((f) => f + statSync(join(dist, f)).size).join('|')).digest('hex').slice(0, 12);
// Directory URLs map to index.html; cache both spellings so navigations hit.
const urls = new Set();
for (const f of precache) {
  urls.add(f);
  if (f.endsWith('/index.html')) urls.add(f.slice(0, -'index.html'.length));
}
const sw = `/* Bleauweb Games service worker, build ${version}. Generated by scripts/make-sw.mjs. */
const CACHE = 'bleauweb-games-${version}';
const PRECACHE = ${JSON.stringify([...urls])};

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    // Add in small batches so one slow file does not fail the whole install.
    for (let i = 0; i < PRECACHE.length; i += 20) {
      await Promise.allSettled(PRECACHE.slice(i, i + 20).map((u) => cache.add(new Request(u, { cache: 'reload' }))));
    }
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    for (const key of await caches.keys()) if (key !== CACHE) await caches.delete(key);
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  if (req.mode === 'navigate') {
    // Pages: try the network for freshness, fall back to the cache when offline.
    event.respondWith((async () => {
      try {
        const fresh = await fetch(req);
        const cache = await caches.open(CACHE);
        cache.put(req, fresh.clone());
        return fresh;
      } catch {
        const cache = await caches.open(CACHE);
        return (await cache.match(req)) || (await cache.match(url.pathname)) || (await cache.match(url.pathname.replace(/\\/$/, '') + '/index.html')) || (await cache.match('/'));
      }
    })());
    return;
  }
  // Everything else is hashed by the build: cache first, then network.
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    const hit = await cache.match(req);
    if (hit) return hit;
    try {
      const fresh = await fetch(req);
      if (fresh.ok) cache.put(req, fresh.clone());
      return fresh;
    } catch {
      return hit || Response.error();
    }
  })());
});
`;
writeFileSync(join(dist, 'sw.js'), sw);
console.log(`sw.js: ${urls.size} entries precached, build ${version}`);
